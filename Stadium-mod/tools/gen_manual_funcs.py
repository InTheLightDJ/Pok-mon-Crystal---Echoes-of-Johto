#!/usr/bin/env python3
"""Make the N64Recomp config for a decomp ELF: base toml + [[input.manual_funcs]].

Some functions in the decomp ELFs are only absolute symbols ("A" in nm: e.g.
osGbpakReadWrite in Stadium 1), not FUNC symbols, so N64Recomp doesn't know a
function starts there and a jal to it fails ("No function found for jal
target"). This lists every absolute symbol inside a code section that isn't
already a function start, sized up to the next symbol in that section, as a
manual function.

Run in WSL (needs mips-linux-gnu binutils):
  python3 tools/gen_manual_funcs.py ELF BASE_TOML OUT_TOML
"""
import subprocess
import sys

elf, base, out = sys.argv[1:4]
# optional: stub_ranges.txt next to the base toml ("start end reason" per line):
# every function found in those ranges is added to [patches] stubs
import os
stub_ranges = []
_sr = os.path.join(os.path.dirname(base), "stub_ranges.txt")
if os.path.exists(_sr):
    for _l in open(_sr, encoding="utf-8"):
        _l = _l.split("#", 1)[0].split()
        if len(_l) >= 2:
            stub_ranges.append((int(_l[0], 16), int(_l[1], 16)))


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


# code sections: name -> (start, end)
sections = {}
section_file_off = {}
for line in run("mips-linux-gnu-readelf", "-S", "-W", elf).splitlines():
    if "PROGBITS" not in line or "]" not in line:
        continue
    parts = line.split("]", 1)[1].split()
    name, _type, addr, _off, size, _es, flags = parts[:7]
    if "X" in flags:
        start = int(addr, 16)
        sections[name] = (start, start + int(size, 16))
        section_file_off[name] = int(_off, 16)
with open(elf, "rb") as _f:
    elf_bytes = _f.read()


def word_at(sec, vram):
    o = section_file_off[sec] + (vram - sections[sec][0])
    return int.from_bytes(elf_bytes[o:o + 4], "big")


def j_target_at(sec, vram):
    """Target of a `j` at vram, else None. (Fragment j targets are 0x8xxxxxxx:
    the game's relocation adds 0x80000000 to the 28-bit field.)"""
    w = word_at(sec, vram)
    if w >> 26 != 2:
        return None
    return 0x80000000 | ((w & 0x3FFFFFF) << 2)


def first_word_j_target(sec):
    """Target of a `j` that is the section's first instruction, else None."""
    return j_target_at(sec, sections[sec][0])

# every symbol address in each section; function starts
funcs = set()
by_section = {name: set() for name in sections}
absolute = []
zero_sized = []   # FUNC symbols with size 0 (hand-written asm without .size): N64Recomp skips them
for line in run("mips-linux-gnu-readelf", "-s", "-W", elf).splitlines():
    p = line.split()
    if len(p) < 8 or not p[0].endswith(":") or not p[0][:-1].isdigit():
        continue
    value, size, typ, ndx, name = int(p[1], 16), p[2], p[3], p[6], p[7]
    for sec, (s, e) in sections.items():
        # hidden fragments (.hf_*) share link addresses with each other and with
        # other symbols: they get their FUNC symbols from build_hidden_fragments.py
        if s <= value < e and not sec.startswith(".hf_"):
            by_section[sec].add(value)
            if ndx == "ABS":       # FUNC or NOTYPE, defined by address only (undefined_funcs_auto.ld...)
                absolute.append((value, name, sec, int(size) if typ == "FUNC" else 0))
            elif typ == "FUNC":
                funcs.add(value)
                if int(size) == 0:
                    zero_sized.append((value, name, sec))
            break

seen = set()
manual = []
for value, name, sec, fsize in sorted(absolute):
    # data labels (D_..., jump tables) can sit in code sections too; functions are word aligned
    if value in funcs or value in seen or value % 4 or name.startswith(("D_", "jtbl_", "jpt_", "L8", ".")):
        continue
    seen.add(value)
    s, e = sections[sec]
    nxt = min([a for a in by_section[sec] if a > value] + [e])
    manual.append((name, sec, value, fsize if fsize > 0 else nxt - value))

with open(base, encoding="utf-8") as f:
    text = f.read().rstrip() + "\n"
text += f"\n# --- generated by tools/gen_manual_funcs.py: {len(manual)} absolute symbols in code ---\n"
for name, sec, value, size in manual:
    text += (f'[[input.manual_funcs]]\nname = "{name}"\nsection = "{sec}"\n'
             f"vram = 0x{value:08X}\nsize = 0x{size:X}\n\n")
# zero-sized functions: sized up to the next symbol in their section, but only
# ones something calls (jal). Others are often jump-table case blocks of a
# bigger function that the decomp tagged as functions (they `j` back into it):
# sizing those breaks the recompile ("Unhandled branch").
import re
jal_targets = set()
j_at = {}   # address -> target of a plain j there
for line in run("mips-linux-gnu-objdump", "-d", "--no-show-raw-insn", elf).splitlines():
    # jal, bal, j (tail calls) to a symbol's exact address all mean "this is called".
    # (Not `bltzal zero, X`: hand asm uses it to read the PC and X is a data table;
    # our patched N64Recomp turns it into just an ra write.)
    mj = re.match(r"\s*([0-9a-f]+):\tj\t([0-9a-f]+)\b", line)
    if mj:
        j_at[int(mj.group(1), 16)] = int(mj.group(2), 16)
    m = re.search(r"\t(?:jal|bal|j)\t([0-9a-f]+) <([^>+]+)>", line)
    if m:
        jal_targets.add(int(m.group(1), 16))
# Stadium fragments start with a header whose first 8 bytes are "j <main>; nop":
# the game calls the fragment's load address, so that stub must be a function.
# Only where the j really goes to +0x20 of the same fragment (one header points
# into another fragment's slot; that one is left out).
# Jump tables right after a fragment header (fragment31's "unk_table": 8-byte
# "j target; nop" slots, many into other fragments) are NOT recompiled: N64Recomp
# can't resolve absolute jumps into another relocatable section. The port
# (port/src/fragments.cpp) registers a thunk per slot when the fragment loads.

for sec, (s, e) in sorted(sections.items(), key=lambda kv: kv[1][0]):
    if (sec.startswith(".fragment") and not sec.startswith(".fragment_") and s not in funcs
            and s not in seen and first_word_j_target(sec) in funcs
            and s <= first_word_j_target(sec) < e):
        seen.add(s)
        manual.append((f"{sec[1:]}_entry", sec, s, 8))
text += "# --- fragment entry stubs ---\n"
for name, sec, value, size in manual:
    if name.startswith("fragment") and name.endswith("_entry"):
        text += (f'[[input.manual_funcs]]\nname = "{name}"\nsection = "{sec}"\n'
                 f"vram = 0x{value:08X}\nsize = 0x{size:X}\n\n")

def in_stub_range(v):
    return any(a <= v < b for a, b in stub_ranges)

# Zero-sized functions in the main code are also called through pointers (e.g. the
# music driver's func_80048AFC), so size every one in 0x80xxxxxx too, except those
# listed in no_size.txt next to the base toml (jump-table case blocks tagged as functions).
no_size = set()
_ns = os.path.join(os.path.dirname(base), "no_size.txt")
if os.path.exists(_ns):
    no_size = {l.split("#", 1)[0].strip() for l in open(_ns, encoding="utf-8")} - {""}

sized = []
for value, name, sec in sorted(zero_sized):
    if name in no_size:
        continue
    if value not in jal_targets and (in_stub_range(value) or not (sec == ".text" and value >> 24 == 0x80)):
        continue
    s, e = sections[sec]
    nxt = min([a for a in by_section[sec] if a > value] + [e])
    size = (nxt - value) & ~3
    if size > 0:
        sized.append((name, size))
text += f"# --- {len(sized)} zero-sized FUNC symbols, sized to the next symbol ---\n"
for name, size in sized:
    text += f'[[input.function_sizes]]\nname = "{name}"\nsize = 0x{size:X}\n\n'

# functions in the stub ranges -> [patches] stubs (callers still link, bodies are empty)
stub_names = sorted({name for value, name, sec in zero_sized if in_stub_range(value) and value in jal_targets} |
                    {name for name, sec, value, size in manual if in_stub_range(value)})
if stub_names:
    marker = "stubs = ["
    i = text.index(marker) + len(marker)
    text = text[:i] + "".join(f'\n    "{n}",  # stub range' for n in stub_names) + text[i:]

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
print(f"{len(sections)} code sections, {len(funcs)} functions, {len(manual)} manual functions, "
      f"{len(sized)} zero-sized functions sized, {len(stub_names)} stubbed by range -> {out}")
for name, size in sized[:12]:
    print(f"  sized {name:28s} 0x{size:X}")
for name, sec, value, size in manual[:15]:
    print(f"  {name:28s} {sec:14s} 0x{value:08X} size 0x{size:X}")
